#!/usr/bin/env python3
"""
indexnow_submit.py — tell search engines a page changed.

IndexNow (indexnow.org) is a free, key-based URL-submission protocol used by
Bing, Yandex, Tandex and other engines. It needs NO account, NO dashboard and
NO human step: a key file published on the site is the entire authentication.

On a daily new page, this is the cheapest real indexing lever available.

Usage:
  python3 pipeline/indexnow_submit.py            # submit all public URLs
  python3 pipeline/indexnow_submit.py --dry-run  # list, don't send

Env:
  SITE_BASE      storefront base URL
  INDEXNOW_KEY   the key; must match a <key>.txt file published at the site root
"""

import argparse
import json
import os
import sys
import urllib.request
import urllib.error
import xml.etree.ElementTree as ET
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from checkout import urllib_request as _rpc_request  # noqa: E402  (shared helper)

DEFAULT_BASE = "https://airdropia.github.io/auto-earn-engine"
ENDPOINTS = [
    "https://api.indexnow.org/indexnow",
    "https://www.bing.com/indexnow",
]


def site_base() -> str:
    return (os.environ.get("SITE_BASE") or DEFAULT_BASE).rstrip("/")


def indexnow_key() -> str:
    key = os.environ.get("INDEXNOW_KEY", "").strip()
    if not key:
        # Fall back to whichever key file exists in site_extra/.
        extra = Path(__file__).resolve().parent.parent / "site_extra"
        for f in extra.glob("*.txt"):
            if len(f.stem) >= 32 and f.stem.isalnum():
                return f.stem
    if not key:
        raise SystemExit("INDEXNOW_KEY not set and no key file found in site_extra/")
    return key


def public_urls() -> list:
    """Every indexable URL: the sitemap is the source of truth."""
    base = site_base()
    urls = [f"{base}/", f"{base}/checkout/"]
    extra = Path(__file__).resolve().parent.parent / "site_extra"
    # Collections and products are known statically from the catalog.
    catalog_path = Path(__file__).resolve().parent.parent / "catalog" / "catalog.json"
    if catalog_path.exists():
        try:
            items = json.loads(catalog_path.read_text(encoding="utf-8"))
            items = items if isinstance(items, list) else items.get("items", [])
        except json.JSONDecodeError:
            items = []
        for it in items:
            pid = it.get("id")
            if pid:
                urls.append(f"{base}/p/{pid}/")
    # Collections are generated by build_site.py; read the live sitemap when
    # reachable so this script never drifts from what was actually published.
    sm = _fetch_text(f"{base}/sitemap.xml")
    if sm:
        try:
            ns = {"s": "http://www.sitemaps.org/schemas/sitemap/0.9"}
            root = ET.fromstring(sm)
            for loc in root.findall(".//s:loc", ns):
                u = (loc.text or "").strip()
                if u.startswith(base) and u not in urls:
                    urls.append(u)
        except ET.ParseError:
            pass
    return urls


def _fetch_text(url: str, timeout: int = 25) -> str:
    try:
        with urllib.request.urlopen(url, timeout=timeout) as r:
            return r.read().decode("utf-8", "replace")
    except Exception:
        return ""


def submit(urls: list, key: str, dry: bool = False) -> dict:
    host = urls[0].split("/")[2] if urls else ""
    key_location = f"{site_base()}/{key}.txt"
    body = json.dumps({
        "host": host,
        "key": key,
        "keyLocation": key_location,
        "urlList": urls,
    }).encode()

    if dry:
        return {"dry_run": True, "host": host, "keyLocation": key_location, "urls": len(urls)}

    results = []
    for endpoint in ENDPOINTS:
        req = urllib.request.Request(
            endpoint, data=body,
            headers={"Content-Type": "application/json; charset=utf-8"},
            method="POST",
        )
        try:
            with urllib.request.urlopen(req, timeout=30) as resp:
                results.append({"endpoint": endpoint, "status": resp.status})
        except urllib.error.HTTPError as e:
            results.append({"endpoint": endpoint, "status": e.code,
                            "detail": e.read().decode("utf-8", "replace")[:200]})
        except Exception as e:
            results.append({"endpoint": endpoint, "status": 0, "detail": str(e)[:200]})
    return {"host": host, "keyLocation": key_location, "urls": len(urls),
            "results": results}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()

    key = indexnow_key()
    urls = public_urls()
    out = submit(urls, key, dry=a.dry_run)
    print(json.dumps(out, indent=2))

    if a.dry_run:
        for u in urls:
            print("  would submit:", u)
        return 0

    ok = any(r.get("status") in (200, 202) for r in out.get("results", []))
    if ok:
        print(f"::notice::IndexNow submitted {len(urls)} URL(s)")
    else:
        print("::warning::IndexNow submission not accepted by any endpoint")
    return 0


if __name__ == "__main__":
    sys.exit(main())
